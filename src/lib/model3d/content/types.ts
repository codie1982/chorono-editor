/** Serializable, asset-revision-bound content. Node transforms are absolute local
 * glTF units/degrees; instance placement is in the scene's metre world, while
 * its uncalibrated geometry retains normalized imported size.
 * No runtime Three objects, dense animation samples or image buffers live here. */
export interface ModelVector { x: number; y: number; z: number }
export interface ModelNodePose { position: ModelVector; rotation: ModelVector; scale: ModelVector; visible: boolean
  /** Scene-local display name; the imported glTF node name and stable ID remain unchanged. */
  name?: string
  /** Optional editor locks and output visibility; old files remain selectable and renderable. */
  frozen?: boolean; renderable?: boolean }
import type { PbrSurface } from '../material/pbrSurface'

export interface ModelMaterial extends PbrSurface {
  color: string; roughness: number; metalness: number; opacity: number
  /** Embedded texture indices, -1 disables the slot; original imported UVs remain intact. */
  map: number; normalMap: number; roughnessMap: number; metalnessMap: number
  /** Optional channels keep older portable scenes readable. */
  aoMap?: number; emissiveMap?: number
}
export interface NativeModelClip {
  clipId: string; inMs: number; outMs: number; speed: number; loop: boolean
  mode: 'play' | 'scrub'; timeMs: number
  /** Revision-bound native channel ownership, checked against decoded inventory. */
  channels: readonly { nodeId: string; field: string }[]
}
export interface ModelContentInstance {
  assetId: string; revision: string; name: string
  /** Absent in older scenes; visible by default. Keeps node visibility intact when the whole instance is hidden. */
  visible?: boolean
  /** Freeze selection in the editor or omit from output while retaining editor visibility. */
  frozen?: boolean; renderable?: boolean
  position: ModelVector; rotation: ModelVector; scale: number
  nodes: Record<string, ModelNodePose>; materials: Record<string, ModelMaterial>
  /** Asset-revision-bound scale from normalized import space to metres. The
   * ordinary instance scale remains independent and composes afterward. */
  calibration?: { revision: string; metersPerNormalizedUnit: number }
  native?: NativeModelClip
}
export interface ModelParameter {
  name: string; type: 'number' | 'boolean'; value: number | boolean
  min: number; max: number; target: string
}
export interface ModelContent {
  version: 1
  instances: Record<string, ModelContentInstance>
  view: { projection: 'perspective' | 'orthographic'; orthoHeight: number }
  light: { position: ModelVector; color: string; shadows: boolean }
  environment: { color: string; intensity: number; exposure: number }
  turntable: { enabled: boolean; speed: number }
  explode: number
  parameters: Record<string, ModelParameter>
  /** Render-only elapsed time; generated by the shared evaluator, never saved by the editor. */
  timeMs?: number
}
export interface ModelNodeInfo extends ModelNodePose { id: string; parentId: string | null; name: string; kind: string; materialIds: readonly string[] }
export interface ModelClipInfo { id: string; name: string; durationMs: number; channels: readonly { nodeId: string; field: string }[] }
/** Immutable decoded inventory borrowed for the lifetime of a prepared lease. */
export interface ModelInventory {
  revision: string; nodes: readonly ModelNodeInfo[]; clips: readonly ModelClipInfo[]
  materials: Readonly<Record<string, ModelMaterial>>; textures: readonly string[]; textureColorSpaces: readonly ('srgb' | 'linear')[]
}
